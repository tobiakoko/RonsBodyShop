/**
 * One-off image pipeline: raw phone JPEGs → responsive AVIF + WebP in public/media/,
 * plus src/content/media.ts with intrinsic dimensions (prevents layout shift).
 *
 * The raw originals (~5–6 MB each) are deliberately NOT committed. Point the
 * script at wherever they live:
 *
 *   npm run optimize-images -- "/path/to/raw/photos"
 *
 * Re-run whenever a photo is added or replaced, then commit public/media and
 * src/content/media.ts.
 */
import sharp from 'sharp';
import { mkdir, readdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('Usage: npm run optimize-images -- <dir-with-raw-photos>');
  process.exit(1);
}
const outDir = 'public/media';

/** key → raw file prefix, output widths, alt text. */
const JOBS = [
  { key: 'shopFront', in: 'IMG_6810', widths: [640, 960, 1280], alt: "Ron's Body Shop building with a vintage Chevy delivery truck out front" },
  { key: 'customerLounge', in: 'IMG_6812', widths: [640, 1024], alt: 'Customer lounge with restored vintage Crown gasoline pumps' },
  { key: 'reception', in: 'IMG_6604', widths: [640, 1024], alt: 'Reception desk and vintage Wurlitzer jukebox' },
  { key: 'awardsWall', in: 'IMG_6815', widths: [640, 1024], alt: 'Wall of certifications and community awards' },
];

const files = await readdir(srcDir);
const find = (prefix, exts) =>
  files.find((f) => f.startsWith(prefix) && exts.includes(path.extname(f).toLowerCase()));

await mkdir(outDir, { recursive: true });
const manifest = {};

for (const job of JOBS) {
  const file = find(job.in, ['.jpeg', '.jpg']);
  if (!file) throw new Error(`No JPEG starting with ${job.in} in ${srcDir}`);
  const base = sharp(path.join(srcDir, file)).rotate(); // honour EXIF orientation
  const meta = await base.clone().metadata();
  // .rotate() swaps axes for orientations 5–8
  const swap = (meta.orientation ?? 1) >= 5;
  const [w0, h0] = swap ? [meta.height, meta.width] : [meta.width, meta.height];
  const slug = job.key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

  for (const w of job.widths) {
    const resized = base.clone().resize({ width: w, withoutEnlargement: true });
    await resized.clone().avif({ quality: 55, effort: 6 }).toFile(`${outDir}/${slug}-${w}.avif`);
    await resized.clone().webp({ quality: 68 }).toFile(`${outDir}/${slug}-${w}.webp`);
  }
  manifest[job.key] = {
    slug,
    widths: job.widths,
    width: job.widths.at(-1),
    height: Math.round((job.widths.at(-1) * h0) / w0),
    alt: job.alt,
  };
  console.log(`✓ ${job.key} (${w0}×${h0}) → ${job.widths.join(', ')}`);
}

// Open Graph / Twitter card image (exactly 1200×630)
const hero = find('IMG_6810', ['.jpeg', '.jpg']);
await sharp(path.join(srcDir, hero)).rotate().resize(1200, 630, { fit: 'cover' }).jpeg({ quality: 78, mozjpeg: true }).toFile('public/og-image.jpg');
console.log('✓ og-image.jpg');

// Logo → lowercase filename
const logo = files.find((f) => /^logo.*\.png$/i.test(f));
if (logo) {
  await copyFile(path.join(srcDir, logo), 'public/logo.png'); // full size, for schema.org / social
  await sharp(path.join(srcDir, logo)).resize(160).webp({ quality: 85 }).toFile(`${outDir}/logo-160.webp`);
  await sharp(path.join(srcDir, logo)).resize(160).png({ compressionLevel: 9 }).toFile(`${outDir}/logo-160.png`);
  console.log('✓ logo.png + 160px variants');
}

const ts = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export interface MediaImage {
  slug: string;
  widths: readonly number[];
  /** Intrinsic size of the largest variant (used for width/height attrs). */
  width: number;
  height: number;
  alt: string;
}

export const MEDIA = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, MediaImage>;
`;
await writeFile('src/content/media.ts', ts);
console.log('✓ src/content/media.ts');
